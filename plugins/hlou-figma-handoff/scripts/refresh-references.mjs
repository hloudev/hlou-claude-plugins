#!/usr/bin/env node
/*
 * node scripts/refresh-references.mjs [--check]
 *
 * Maintainers only, from a checkout of the Hlou repository: regenerates the
 * reference files the skill ships from their sources —
 *
 *   reference/phosphor-icons.txt   the icon names Hlou's renderer bundles
 *   reference/google-fonts.txt     the offline Google Fonts catalogue
 *   reference/hints.md             the section hints and their meaning
 *   reference/handoff.schema.json  the generated JSON Schema, copied
 *   reference/example-manifest.json the contract's minimal fixture, copied
 *
 * `--check` writes nothing and exits 1 when a file is out of date.
 * reference/conventions.md is written by hand.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const REFERENCE_DIR = path.join(here, '..', 'reference');

/** The repository root above the plugin folder, or null (a published copy). */
export function findRepoRoot(from = here) {
  let dir = from;
  for (;;) {
    if (
      existsSync(path.join(dir, 'pnpm-workspace.yaml')) &&
      existsSync(path.join(dir, 'packages', 'contracts'))
    ) {
      return dir;
    }
    const parent = path.dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

export const SOURCES = {
  icons: 'packages/site-renderer/src/blocks/icon-paths.ts',
  fonts: 'packages/site-renderer/src/theme/google-fonts-catalog.ts',
  contract: 'packages/contracts/src/handoff/index.ts',
  schema: 'packages/contracts/src/handoff/handoff.schema.json',
  example: 'packages/contracts/src/handoff/__fixtures__/minimal/hlou-handoff.json',
};

/** The keys of `ICON_PATHS`, in source order. */
export function iconNames(source) {
  const start = source.indexOf('ICON_PATHS');
  const body = source.slice(start, source.indexOf('\n};', start));
  return [...body.matchAll(/^ {2}(?:'([a-z0-9-]+)'|([a-z0-9]+)): \[/gm)].map((m) => m[1] ?? m[2]);
}

/** Every `family: '…'` of the catalogue, in popularity order. */
export function fontFamilies(source) {
  return [...source.matchAll(/family: '((?:[^'\\]|\\.)+)'/g)].map((m) => m[1].replace(/\\'/g, "'"));
}

/** `HANDOFF_HINTS` as `[hint, meaning][]`. */
export function hintEntries(source) {
  const start = source.indexOf('export const HANDOFF_HINTS');
  const body = source.slice(start, source.indexOf('} as const;', start));
  return [...body.matchAll(/^ {2}(?:'([^']+)'|([\w-]+)): '((?:[^'\\]|\\.)*)',$/gm)].map((m) => [
    m[1] ?? m[2],
    m[3].replace(/\\'/g, "'"),
  ]);
}

/** A Markdown table padded the way Prettier pads it, so a formatter leaves it alone. */
function table(header, rows) {
  const all = [header, ...rows];
  const widths = header.map((_, i) => Math.max(3, ...all.map((row) => row[i].length)));
  const line = (row) => `| ${row.map((cell, i) => cell.padEnd(widths[i])).join(' | ')} |`;
  return [line(header), `| ${widths.map((w) => '-'.repeat(w)).join(' | ')} |`, ...rows.map(line)];
}

function hintsMarkdown(entries) {
  return [
    '# Section hints',
    '',
    'Written into `pages[].sections[].hints`. Documented, not enforced: an unknown hint is',
    'read as plain text. `<key>` is a collection key, `<n>` a count. Generated by',
    '`scripts/refresh-references.mjs`; do not edit by hand.',
    '',
    ...table(
      ['Hint', 'Means'],
      entries.map(([hint, meaning]) => [`\`${hint}\``, meaning])
    ),
    '',
  ].join('\n');
}

/** `{ file → expected text }` for every generated reference file. */
export function expectedReferences(root) {
  const read = (key) => readFileSync(path.join(root, SOURCES[key]), 'utf8');
  return {
    'phosphor-icons.txt': `${iconNames(read('icons')).join('\n')}\n`,
    'google-fonts.txt': `${fontFamilies(read('fonts')).join('\n')}\n`,
    'hints.md': hintsMarkdown(hintEntries(read('contract'))),
    'handoff.schema.json': read('schema'),
    'example-manifest.json': read('example'),
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const root = findRepoRoot();
  if (!root) {
    console.error('Run this from a checkout of the Hlou repository.');
    process.exit(2);
  }
  let stale = 0;
  for (const [file, text] of Object.entries(expectedReferences(root))) {
    const target = path.join(REFERENCE_DIR, file);
    const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
    if (current === text) continue;
    stale++;
    if (check) console.log(`stale reference/${file}`);
    else {
      writeFileSync(target, text);
      console.log(`wrote reference/${file}`);
    }
  }
  if (check && stale > 0) process.exit(1);
  if (stale === 0) console.log('references up to date');
}
